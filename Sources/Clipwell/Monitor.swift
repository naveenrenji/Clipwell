import AppKit

/// One clipboard change, read off the pasteboard and tagged with the app that produced it.
struct Capture {
    enum Payload {
        case text(String)
        /// Raw pasteboard bytes (PNG or TIFF). Decoding and encoding happen off the main thread.
        case image(Data)
        case files([String])
    }

    let payload: Payload
    let sourceApp: String?
    let sourceBundle: String?
}

/// Watches `NSPasteboard.general` by change count (cheap integer compare every 0.35s)
/// and reports new content. Respects the nspasteboard.org conventions password managers use.
final class ClipboardMonitor {
    static let maxTextBytes = 2_000_000
    static let maxImageBytes = 30_000_000

    /// Copies flagged with these types are secrets or transient data; never record them.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Apps whose copies are never recorded, whatever they put on the pasteboard.
    private static let builtInExcludedBundles: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
    ]

    var onCapture: ((Capture) -> Void)?
    var isPaused = false

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var previousFront: NSRunningApplication?
    private var timer: Timer?

    func start() {
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after writing to the pasteboard ourselves so a paste from history is not recorded again.
    func ignoreCurrentChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let front = NSWorkspace.shared.frontmostApplication
        defer { previousFront = front }

        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        // The copy happened somewhere in the last tick. If the frontmost app changed during it,
        // the usual cause is "copy, then switch away", so credit the app that was frontmost before.
        var source = front
        if let previous = previousFront, previous.processIdentifier != front?.processIdentifier, !previous.isTerminated {
            source = previous
        }

        if let bundle = source?.bundleIdentifier,
           Self.builtInExcludedBundles.contains(bundle) || Settings.excludedBundles.contains(bundle) { return }

        guard let payload = readPayload(pb, types: types) else { return }
        onCapture?(Capture(payload: payload, sourceApp: source?.localizedName, sourceBundle: source?.bundleIdentifier))
    }

    private func readPayload(_ pb: NSPasteboard, types: Set<String>) -> Capture.Payload? {
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls.map(\.path))
        }
        if types.contains(NSPasteboard.PasteboardType.string.rawValue),
           let text = pb.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= Self.maxTextBytes else { return nil }
            return .text(text)
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count <= Self.maxImageBytes {
            return .image(data)
        }
        return nil
    }
}
